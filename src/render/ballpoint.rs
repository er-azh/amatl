fn perm(i: u32) -> u32 {
    PERM[(i & 0xff) as usize] as u32
}

/// Lattice value at (x, y): P[(x & 255) + P[y & 255]] over the doubled table.
pub fn lattice(x: i32, y: i32) -> u32 {
    perm((x as u32 & 0xff) + perm(y as u32))
}

/// floor() as xochitl computes it: truncate, minus one when negative. Returns (i0, i1, frac*255).
fn split(f: f32) -> (i32, i32, i32) {
    let t = f as i32;
    let (i0, i1) = if f < 0.0 { (t - 1, t) } else { (t, t + 1) };
    (i0, i1, ((f - i0 as f32) * 255.0) as i32)
}

pub fn noise(u: f32, v: f32) -> u32 {
    let (x0, x1, fx) = split(u);
    let (y0, y1, fy) = split(v);
    let top = (255 - fx) * lattice(x0, y0) as i32 + fx * lattice(x1, y0) as i32;
    let bot = (255 - fx) * lattice(x0, y1) as i32 + fx * lattice(x1, y1) as i32;
    (((255 - fy) * top + fy * bot) >> 16) as u32
}

/// Ballpoint intensity (0..=255) from point pressure and speed.
pub fn intensity(p: &Point) -> i32 {
    let pf = p.pressure as f32 / 255.0;
    let a = if pf <= 0.7 {
        let t = pf / 0.7;
        (3.0 - (t + t)) * t * t * 0.5 + 0.5
    } else {
        1.0
    };
    let s = p.speed as f32 / 4.0;
    let b = if s < 5.0 {
        255.0
    } else if s <= 30.0 {
        let t = (s - 5.0) / 25.0;
        255.0 - (3.0 - (t + t)) * t * t * 50.0
    } else {
        205.0
    };
    let i = a * b;
    if i > 0.0 { i as i32 } else { 0 }
}

pub struct Fill<'a> {
    pub canvas: &'a mut Canvas,
    pub color: u32,
    pub threshold: u32,
    pub vscale: f32,
    /// Triangles are clipped to this box before scan conversion.
    pub clip: ClipBox,
}

impl SpanFill for Fill<'_> {
    fn span(&mut self, x0: i32, x1: i32, y: i32, v: Var, dv: Var) {
        let (mut a, mut b) = (v[0], v[1]);
        let (da, db) = (dv[0], dv[1]);
        for x in x0..x1 {
            let (u, w) = (a, b * self.vscale);
            a += da;
            b += db;
            if noise(u, w) < self.threshold {
                self.canvas.put(x, y, self.color);
            }
        }
    }
}

impl Raster for Fill<'_> {
    fn triangle(&mut self, a: Vertex, b: Vertex, c: Vertex, va: Var, vb: Var, vc: Var) {
        clip_triangle(
            self.clip,
            a,
            b,
            c,
            va,
            vb,
            vc,
            &mut |a, b, c, va, vb, vc| lerp_triangle(self, a, b, c, va, vb, vc),
        );
    }
}

pub fn draw(r: &mut Renderer, line: &Line) {
    let scale = r.scale;
    let t = r.transform();
    let clip = r.clip_box();
    let mut st = Stroker::new(WidthLength {
        k1: 0.01 / scale,
        k2: 1.0,
    });
    st.join = Join::Round;
    st.cap = Cap::Round;
    st.length = line.starting_length * scale;
    let mut fill = Fill {
        canvas: &mut r.canvas,
        color: premultiply(line.color.to_argb(line.argb)),
        threshold: 0,
        vscale: 1.0 / scale,
        clip,
    };
    for p in &line.points {
        let (x, y) = t.map(p.x, p.y);
        fill.threshold = intensity(p) as u32;
        st.width = p.width as f32 / 4.0 * scale;
        st.line_to(&mut fill, x, y);
        st.start_cap(&mut fill);
    }
    st.finish(&mut fill);
}
